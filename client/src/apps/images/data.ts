/** The order folders are shown in. */
export const FOLDERS = ['Brand', 'Photography', 'Ad creative', 'Website'];

/** Lower case: a meta line's first letter is capitalised by CSS. */
export const KIND_WORDS: Record<Kind, string> = {
  logo: 'logo',
  photo: 'photo',
  ad: 'ad creative',
  screenshot: 'screenshot',
};

const FOLDER_PATHS: Record<string, string> = {
  Brand: 'context/brand',
  Photography: 'context/reference/photos',
  'Ad creative': 'created/2026-10-20-ad-creative',
  Website: 'website',
};

type Row = [
  folder: string,
  kind: Kind,
  name: string,
  width: number,
  height: number,
  kb: number,
  added: string,
  by: string,
  scene: Scene,
  tone: Tone,
  tags: string,
  usedIn?: string[],
];

function rows(client: string, list: Row[]): LibraryImage[] {
  return list.map(([folder, kind, name, width, height, kb, added, by, scene, tone, tags, usedIn]) => ({
    id: `${client}/${name}`,
    client,
    folder,
    kind,
    name,
    path: `clients/${client}/${FOLDER_PATHS[folder] ?? 'context/reference'}/${name}`,
    width,
    height,
    bytes: kb * 1000,
    added,
    by,
    tags: tags.split(' '),
    usedIn: usedIn ?? [],
    art: { scene, tone },
  }));
}


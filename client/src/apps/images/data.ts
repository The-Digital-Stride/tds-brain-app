/**
 * Sample data for the example Images app. Nothing here is read from a brain: the two clients are
 * the pretend ones the preview uses, and every picture is drawn in code (see `Art.tsx`).
 */

export type Kind = 'logo' | 'photo' | 'ad' | 'screenshot';
export type Scene = 'logo' | 'van' | 'engineer' | 'boiler' | 'radiator' | 'house' | 'team' | 'ad' | 'site';
export type Tone = 'light' | 'dark' | 'clear' | 'mono' | 'warm' | 'cool';

export interface LibraryImage {
  id: string;
  /** Client folder name, e.g. "acme-heating". */
  client: string;
  folder: string;
  kind: Kind;
  name: string;
  /** Where the file would sit in the brain. */
  path: string;
  width: number;
  height: number;
  bytes: number;
  /** YYYY-MM-DD. */
  added: string;
  by: string;
  tags: string[];
  /** Where the image is in use, e.g. "Google Ads: Boiler service". */
  usedIn: string[];
  art: { scene: Scene; tone: Tone };
}

export interface LibraryClient {
  slug: string;
  name: string;
  brand: { main: string; dark: string; accent: string };
}

